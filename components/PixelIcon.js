export default function PixelIcon({ type, size = 32 }) {
  const icon = icons[type];
  if (!icon) return null;

  const renderGrid = () => (
    icon.pixels.map((row, y) => (
      row.split('').map((char, x) => (
        char !== '0' ? <rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill={icon.colors[char]} /> : null
      ))
    ))
  );

  return (
    <svg 
      viewBox="0 0 12 12" 
      width={size} 
      height={size}
      style={{ filter: 'drop-shadow(2px 2px 0px rgba(0,0,0,0.3))' }}
    >
      {renderGrid()}
    </svg>
  );
}
